#pragma once

// 「今カーソルの位置で建設すると、いくらかかるか」の表示用の値。
// 建物の配置・道路の配置が毎フレーム書き込み、HUD(カーソルの横の小さなタグ)が読んで描く。
// GameContext(各システムが書く側)とHudState(UIが読む側)の両方が同じこの型を使うので、
// UIは建物・道路のどちらの処理も知らずに、この値だけを見て描ける。
struct CostPreview
{
    bool visible = false;     // タグを出すか(建設ツールでワールド上にカーソルがある間だけtrue)
    int cost = 0;             // かかる金額(円)
    int cells = 0;            // 道路のマス数(道路の時だけ。0なら金額だけを表示する=建物)
    bool affordable = true;   // 今の所持金で払えるか(falseなら「お金が足りません」を出す)
};
