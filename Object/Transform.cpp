void Transform::SyncEulerFromQuaternion()
{
    using namespace DirectX;

    //========================================================
    // QuaternionÇê≥ãKâªÇµÇƒéÊìæ
    //========================================================
    XMVECTOR q =
        XMLoadFloat4(&rotationQuat);

    q =
        XMQuaternionNormalize(q);

    //========================================================
    // Quaternion Å® âÒì]çsóÒ
    //========================================================
    XMMATRIX m =
        XMMatrixRotationQuaternion(q);

    //========================================================
    // âÒì]çsóÒ Å® Euleräp
    //
    // XMMatrixRotationRollPitchYaw(pitch, yaw, roll)
    // Ç∆ìØÇ∂èáî‘Ç…ñﬂÇ∑
    //
    // rotation.x = Pitch(X)
    // rotation.y = Yaw(Y)
    // rotation.z = Roll(Z)
    //========================================================
    float pitch;
    float yaw;
    float roll;

    pitch =
        asinf(-m.r[2].m128_f32[1]);

    float cosPitch =
        cosf(pitch);

    if (fabsf(cosPitch) > 0.0001f)
    {
        yaw =
            atan2f(
                m.r[2].m128_f32[0],
                m.r[2].m128_f32[2]
            );

        roll =
            atan2f(
                m.r[0].m128_f32[1],
                m.r[1].m128_f32[1]
            );
    }
    else
    {
        yaw =
            atan2f(
                -m.r[0].m128_f32[2],
                m.r[0].m128_f32[0]
            );

        roll = 0.0f;
    }

    //========================================================
    // Inspectorï\é¶ópEulerÇ÷ï€ë∂
    //========================================================
    rotation =
    {
        pitch,
        yaw,
        roll
    };

    //========================================================
    // ê≥ãKâªçœÇ›QuaternionÇ‡ï€ë∂
    //========================================================
    XMStoreFloat4(
        &rotationQuat,
        q
    );
}