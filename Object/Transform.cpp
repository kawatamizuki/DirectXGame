XMMATRIX Transform::GetWorldMatrix() const
{
    //========================================================
    // ScaleçsóÒ
    //========================================================
    XMMATRIX s =
        XMMatrixScaling(
            scale.x,
            scale.y,
            scale.z
        );

    //========================================================
    // Quaternionì«çû
    //========================================================
    XMVECTOR q =
        XMLoadFloat4(&rotationQuat);

    //========================================================
    // îOÇÃÇΩÇﬂê≥ãKâª
    //
    // QuaternionÇÕââéZÇåJÇËï‘Ç∑Ç∆
    // è≠ÇµÇ∏Ç¬åÎç∑Ç≈í∑Ç≥Ç™1Ç©ÇÁÉYÉåÇÈ
    //========================================================
    q =
        XMQuaternionNormalize(q);

    //========================================================
    // Quaternion Å® âÒì]çsóÒ
    //========================================================
    XMMATRIX r =
        XMMatrixRotationQuaternion(q);

    //========================================================
    // ïΩçsà⁄ìÆçsóÒ
    //========================================================
    XMMATRIX t =
        XMMatrixTranslation(
            position.x,
            position.y,
            position.z
        );

    //========================================================
    // WorldçsóÒê∂ê¨
    //
    // DirectXÇ≈ÇÕ
    // Scale Å® Rotation Å® Translation
    // ÇÃèáÇ≈ä|ÇØÇÈ
    //========================================================
    return s * r * t;
}

