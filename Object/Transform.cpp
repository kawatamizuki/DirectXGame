void Transform::SetRotationEuler( const DirectX::XMFLOAT3& euler)
{
    //========================================================
    // Euleräpï€ë∂
    //
    // Inspectorï\é¶óp
    //========================================================
    rotation = euler;

    //========================================================
    // Euleräp Å® Quaternionïœä∑
    //
    // rotation.x = Pitch
    // rotation.y = Yaw
    // rotation.z = Roll
    //========================================================
    XMVECTOR q =
        XMQuaternionRotationRollPitchYaw(
            rotation.x,
            rotation.y,
            rotation.z
        );

    //========================================================
    // ê≥ãKâª
    //========================================================
    q =
        XMQuaternionNormalize(q);

    //========================================================
    // TransformÇ÷ï€ë∂
    //========================================================
    XMStoreFloat4(
        &rotationQuat,
        q
    );
}

