#include "Transform.h"

using namespace DirectX;

//============================================================
// Transformのワールド行列生成
//
// Scale → Rotation(Quaternion) → Translation
//
// Quaternionを使うことで
// ・ジンバルロック回避
// ・回転軸のズレ防止
// ・Rotate Gizmoとの相性向上
//============================================================
XMMATRIX Transform::GetWorldMatrix() const
{
    //========================================================
    // Scale行列
    //========================================================
    XMMATRIX s =
        XMMatrixScaling(
            scale.x,
            scale.y,
            scale.z
        );

    //========================================================
    // Quaternion読込
    //========================================================
    XMVECTOR q =
        XMLoadFloat4(&rotationQuat);

    //========================================================
    // 念のため正規化
    //
    // Quaternionは演算を繰り返すと
    // 少しずつ誤差で長さが1からズレる
    //========================================================
    q =
        XMQuaternionNormalize(q);

    //========================================================
    // Quaternion → 回転行列
    //========================================================
    XMMATRIX r =
        XMMatrixRotationQuaternion(q);

    //========================================================
    // 平行移動行列
    //========================================================
    XMMATRIX t =
        XMMatrixTranslation(
            position.x,
            position.y,
            position.z
        );

    //========================================================
    // World行列生成
    //
    // DirectXでは
    // Scale → Rotation → Translation
    // の順で掛ける
    //========================================================
    return s * r * t;
}

//============================================================
// Euler角からQuaternionを生成する
//
// Inspectorなどから回転を変更するときに使用
//============================================================
void Transform::SetRotationEuler( const DirectX::XMFLOAT3& euler)
{
    //========================================================
    // Euler角保存
    //
    // Inspector表示用
    //========================================================
    rotation = euler;

    //========================================================
    // Euler角 → Quaternion変換
    //
    // rotation.x = Pitch
    // rotation.y = Yaw
    // rotation.z = Roll
    //========================================================
    XMVECTOR q =
        XMQuaternionRotationRollPitchYaw(
            rotation.x,
            rotation.y,
            rotation.z
        );

    //========================================================
    // 正規化
    //========================================================
    q =
        XMQuaternionNormalize(q);

    //========================================================
    // Transformへ保存
    //========================================================
    XMStoreFloat4(
        &rotationQuat,
        q
    );
}

//============================================================
// Quaternion正規化
//
// Quaternion合成を繰り返した後に呼ぶ
// 誤差蓄積防止用
//============================================================
void Transform::NormalizeRotation()
{
    //========================================================
    // Quaternion読込
    //========================================================
    XMVECTOR q =
        XMLoadFloat4(&rotationQuat);

    //========================================================
    // 長さ1へ補正
    //========================================================
    q =
        XMQuaternionNormalize(q);

    //========================================================
    // 保存
    //========================================================
    XMStoreFloat4(
        &rotationQuat,
        q
    );
}

void Transform::SyncEulerFromQuaternion()
{
    using namespace DirectX;

    //========================================================
    // Quaternionを正規化して取得
    //========================================================
    XMVECTOR q =
        XMLoadFloat4(&rotationQuat);

    q =
        XMQuaternionNormalize(q);

    //========================================================
    // Quaternion → 回転行列
    //========================================================
    XMMATRIX m =
        XMMatrixRotationQuaternion(q);

    //========================================================
    // 回転行列 → Euler角
    //
    // XMMatrixRotationRollPitchYaw(pitch, yaw, roll)
    // と同じ順番に戻す
    //
    // rotation.x = Pitch(X)
    // rotation.y = Yaw(Y)
    // rotation.z = Roll(Z)
    //========================================================
    float pitch;
    float yaw;
    float roll;

    pitch =
        asinf(-m.r[2].m128_f32[1]);

    float cosPitch =
        cosf(pitch);

    if (fabsf(cosPitch) > 0.0001f)
    {
        yaw =
            atan2f(
                m.r[2].m128_f32[0],
                m.r[2].m128_f32[2]
            );

        roll =
            atan2f(
                m.r[0].m128_f32[1],
                m.r[1].m128_f32[1]
            );
    }
    else
    {
        yaw =
            atan2f(
                -m.r[0].m128_f32[2],
                m.r[0].m128_f32[0]
            );

        roll = 0.0f;
    }

    //========================================================
    // Inspector表示用Eulerへ保存
    //========================================================
    rotation =
    {
        pitch,
        yaw,
        roll
    };

    //========================================================
    // 正規化済みQuaternionも保存
    //========================================================
    XMStoreFloat4(
        &rotationQuat,
        q
    );
}